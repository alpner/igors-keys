"""Writes build/version_info.txt, the Windows version resource PyInstaller puts into IgorsKeys.exe.

An exe without file details (description, product name, version) looks more suspicious to antivirus programs,
and the details also show in the file's Properties and in Windows' warning dialogs.  The version is read from
igorskeys/__init__.py, so it still lives in one place.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))

TEMPLATE = """# generated by make_version.py - do not edit
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={tuple}, prodvers={tuple},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('FileDescription', {description!r}),
        StringStruct('ProductName', "Igor's Keys"),
        StringStruct('FileVersion', {version!r}),
        StringStruct('ProductVersion', {version!r}),
        StringStruct('InternalName', 'IgorsKeys'),
        StringStruct('OriginalFilename', 'IgorsKeys.exe'),
        StringStruct('LegalCopyright', {copyright!r}),
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [0x0409, 1200])])
  ]
)
"""


def main():
    init = open(os.path.join(HERE, "igorskeys", "__init__.py"), encoding="utf-8").read()
    version = re.search(r'__version__\s*=\s*"([^"]+)"', init).group(1)
    numbers = [int(n) for n in re.findall(r"\d+", version)][:4]
    numbers += [0] * (4 - len(numbers))
    licence = open(os.path.join(HERE, "..", "LICENSE"), encoding="utf-8").read()
    copyright_line = next(l.strip() for l in licence.splitlines() if l.startswith("Copyright"))
    text = TEMPLATE.format(
        tuple=tuple(numbers), version=version, copyright=copyright_line,
        description="Igor's Keys - extra keys for the CHERRY CyMotion Master XPress (unofficial)")
    out_dir = os.path.join(HERE, "build")
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "version_info.txt"), "w", encoding="utf-8") as f:
        f.write(text)
    print("version_info.txt written for", version)


if __name__ == "__main__":
    main()
